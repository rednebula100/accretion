import { chromium } from 'playwright';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const url = process.env.TEST_URL || 'https://rednebula100.github.io/accretion/';
const local = `${process.env.LOCALAPPDATA}/ms-playwright/chromium-1228/chrome-win64/chrome.exe`;
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || (fs.existsSync(local) ? local : undefined) });
const out = 'test-results/github-pages';
fs.mkdirSync(out, { recursive: true });
try {
  const context = await browser.newContext({ viewport: { width: 1366, height: 768 } });
  const page = await context.newPage();
  const errors = [], assets = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('response', r => { if (r.status() >= 400) errors.push(`${r.status()} ${r.url()}`); assets.push(r.url()); });
  page.on('requestfailed', r => errors.push(`${r.failure()?.errorText} ${r.url()}`));
  const response = await page.goto(url);
  assert.equal(response.status(), 200);
  await page.locator('[data-action="matter"][data-id="0"]:visible').waitFor();
  assert.equal(await page.evaluate(() => typeof window.__ACCRETION_DEBUG__), 'undefined');
  const before = await page.locator('#mass').textContent();
  await page.locator('[data-action="matter"][data-id="0"]:visible').click();
  await page.waitForTimeout(5500);
  assert.notEqual(await page.locator('#mass').textContent(), before);
  await page.locator('#settings-open').click();
  await page.locator('#motion').check();
  const download = page.waitForEvent('download');
  await page.locator('#export').click();
  await (await download).saveAs(`${out}/save.json`);
  const save = JSON.parse(fs.readFileSync(`${out}/save.json`, 'utf8'));
  assert.ok(save.seen.includes(0));
  await page.locator('#settings-close').click();
  await page.waitForTimeout(5500);
  await page.reload();
  await page.locator('#settings-open').click();
  assert.equal(await page.locator('#motion').isChecked(), true);
  assert.ok(await page.evaluate(() => JSON.parse(localStorage.getItem('accretion.save.v3')).seen.includes(0)));
  await page.locator('#settings-close').click();
  await page.screenshot({ path: `${out}/live.png` });
  assert.ok(assets.some(a => a.includes('matter-atlas.png')));
  assert.ok(assets.some(a => a.includes('.woff2')));
  assert.deepEqual(errors, []);
  const result = { url, passed: true, checks: ['anonymous access', 'asset loading', 'Matter purchase and absorption', 'save export', 'reload persistence', 'settings persistence', 'no runtime errors'] };
  fs.writeFileSync(`${out}/result.json`, JSON.stringify(result, null, 2));
  console.log(JSON.stringify(result));
} finally { await browser.close(); }
